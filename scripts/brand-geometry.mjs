/**
 * Measures the KIKI logo and derives everything the site needs to use the
 * real letterforms:
 *   - lib/brand-geometry.ts   letter box + per-letter slots (normalised 0..1)
 *   - public/brand/*.png      wordmark, per-letter masks and dilated outline masks
 *
 * Input is the vector-traced logo written by scripts/vectorize-logo.mjs.
 *
 *   node scripts/vectorize-logo.mjs && node scripts/brand-geometry.mjs
 */
import sharp from "sharp";
import { mkdir, writeFile, rm } from "node:fs/promises";

const LOGO = "assets/source/15-kiki-logo-traced.png";
const OUTLINE_PAD = 16; // px of dilation room around each letter mask, at source scale
await mkdir("public/brand", { recursive: true });
for (const stale of ["kiki-wordmark-flowers.png", "kiki-flowers-only.png"]) await rm(`public/brand/${stale}`, { force: true });

const { data, info } = await sharp(LOGO).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const { width: W, height: H } = info;
const ink = (x, y) => data[(y * W + x) * 4 + 3] > 128;

/* Ink bounds of the whole mark. */
let x0 = W, x1 = 0, y0 = H, y1 = 0;
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (ink(x, y)) {
  if (x < x0) x0 = x;
  if (x > x1) x1 = x;
  if (y < y0) y0 = y;
  if (y > y1) y1 = y;
}
const lw = x1 - x0 + 1;
const lh = y1 - y0 + 1;

/* Letters: runs of inked columns, merging the engraved inline with its stem. */
const cols = new Uint32Array(W);
for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) if (ink(x, y)) cols[x]++;
const runs = [];
let start = -1;
for (let x = x0; x <= x1 + 1; x++) {
  const on = x <= x1 && cols[x] > 0;
  if (on && start < 0) start = x;
  if (!on && start >= 0) {
    runs.push({ x0: start, x1: x - 1 });
    start = -1;
  }
}
const gaps = runs.slice(1).map((r, i) => r.x0 - runs[i].x1 - 1).sort((a, b) => b - a);
// The three widest gaps separate the four letters; everything narrower is inside a letter.
const letterGap = gaps[2];
const slots = [];
for (const r of runs) {
  const last = slots[slots.length - 1];
  if (last && r.x0 - last.x1 - 1 < letterGap) last.x1 = r.x1;
  else slots.push({ ...r });
}
console.log("logo", W, "x", H, "ink box", { x0, y0, lw, lh }, "letter gap", letterGap, "slots", slots);
if (slots.length !== 4) throw new Error(`expected 4 letters, found ${slots.length}`);

const ids = ["k1", "i1", "k2", "i2"];
const slotMeta = [];
for (let i = 0; i < 4; i++) {
  const s = slots[i];
  const w = s.x1 - s.x0 + 1;
  await sharp(LOGO).extract({ left: s.x0, top: y0, width: w, height: lh }).png().toFile(`public/brand/mask-${ids[i]}.png`);
  const P = OUTLINE_PAD;
  const alpha = await sharp(LOGO)
    .extract({ left: s.x0, top: y0, width: w, height: lh })
    .extend({ top: P, bottom: P, left: P, right: P, background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .ensureAlpha()
    .extractChannel(3)
    .blur(6)
    .threshold(10)
    .toBuffer();
  await sharp({ create: { width: w + 2 * P, height: lh + 2 * P, channels: 3, background: "#ffffff" } })
    .joinChannel(alpha)
    .png()
    .toFile(`public/brand/outline-${ids[i]}.png`);
  slotMeta.push({ id: ids[i], x: (s.x0 - x0) / lw, w: w / lw });
}

await sharp(LOGO).png({ compressionLevel: 9 }).toFile("public/brand/kiki-wordmark.png");

const ts = `/**
 * GENERATED by scripts/brand-geometry.mjs from the traced KIKI logo. Do not edit by hand.
 * All values are fractions of the KIKI letter box (the four letters' ink bounds).
 */
export const BRAND_GEOMETRY = {
  /** Letter box aspect: height / width. */
  letterAspect: ${(lh / lw).toFixed(5)},
  /** Per-letter slots inside the letter box. */
  slots: ${JSON.stringify(slotMeta)},
  /** Dilation padding of the outline masks, as a fraction of the letter box width/height. */
  outlinePad: { x: ${(OUTLINE_PAD / lw).toFixed(5)}, y: ${(OUTLINE_PAD / lh).toFixed(5)} },
  /** The logo image, and where the letter box sits inside it. */
  wordmark: { src: "/brand/kiki-wordmark.png", svg: "/brand/kiki-logo.svg", width: ${W}, height: ${H}, letter: { x: ${(x0 / W).toFixed(5)}, y: ${(y0 / H).toFixed(5)}, w: ${(lw / W).toFixed(5)}, h: ${(lh / H).toFixed(5)} } },
} as const;
`;
await writeFile("lib/brand-geometry.ts", ts);
